// Паттерны уровня, нарисованные текстом.
// Каждая строка — один ряд сетки, 12 колонок = полный круг.
// ВЕРХНЯЯ строка — дальняя (выход), НИЖНЯЯ — ближняя (вход).
//
//   .  пол
//   1  препятствие высотой 1 уровень (2 м) — будка, шкафы, ящики, кондиционер
//   2  2 уровня — контейнеры
//   3  3 уровня — пристройка
//   #  высотка — стена, врезаться нельзя
//   w  красная стена — по ней можно бежать (свайп в её сторону)
//   b  низкий мост на улице / трубы в тоннеле — только подкатом (свайп вниз)
//   _  пропасть: между крышами, канал на улице, дыра в пустоту в тоннеле
//   ~  бассейн в подземке
//   L  красный трамплин на крыше — подбрасывает на верхушку небоскрёба (через 4 ряда)
//
// Ярусы (tier): street — улица, roof — по крышам (пол на 8 м), under — тоннели (пол на −6 м),
// sky — по верхушкам небоскрёбов (пол на 40 м).
// Переходы: tier → to, а base — высота пола каждого ряда (сверху вниз, как rows):
// число — ровный пол, [a, b] — рампа от a (ближний край) до b (дальний).
// vision: true — предметы паттерна подсвечены красным, как в Mirror's Edge: «по этому — наверх».
//
// Генератор сам поворачивает паттерн по кругу и может отзеркалить его,
// поэтому рисовать можно в любом месте строки.
// diff — сложность (1..3), weight — как часто встречается.

