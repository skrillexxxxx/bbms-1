// Паттерны уровня, нарисованные текстом.
// Каждая строка — один ряд сетки, 12 колонок = полный круг.
// ВЕРХНЯЯ строка — дальняя (выход), НИЖНЯЯ — ближняя (вход).
//
//   .  улица (уровень земли)
//   1  крыша низкого здания, высота 1 уровень (можно запрыгнуть с земли)
//   2  крыша, 2 уровня
//   3  крыша, 3 уровня
//   #  высотка — стена, врезаться нельзя
//   b  улица под низким мостом — проехать только подкатом (свайп вниз)
//      (в тоннеле — низкие трубы под потолком)
//   _  пропасть между крышами — только перепрыгнуть
//
// Ярусы (tier): street — улица, roof — по крышам (пол на 12 м), under — тоннели (пол на −6 м).
// Переходы: tier → to, а base — высота пола каждого ряда (сверху вниз, как rows):
// число — ровный пол, [a, b] — рампа от a (ближний край) до b (дальний).
//
// Генератор сам поворачивает паттерн по кругу и может отзеркалить его,
// поэтому рисовать можно в любом месте строки.
// diff — сложность (1..3), weight — как часто встречается.

